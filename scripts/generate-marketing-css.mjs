import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'
import { gzipSync } from 'node:zlib'
import postcss from 'postcss'
import selectorParser from 'postcss-selector-parser'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const sourceRoot = path.join(root, 'src')
const app = path.join(sourceRoot, 'app')
const writing = process.argv.includes('--write')
const visited = new Set()
function visit(file) {
  if (visited.has(file) || !fs.existsSync(file)) return
  visited.add(file)
  const text = fs.readFileSync(file, 'utf8')
  for (const match of text.matchAll(/(?:from\s*|import\s*\(\s*)['"](@\/[^'"]+|\.[^'"]+)['"]/g)) {
    const base = match[1].startsWith('@/') ? path.join(sourceRoot, match[1].slice(2)) : path.resolve(path.dirname(file), match[1])
    const dependency = ['.tsx', '.ts', '.jsx', '.js', '/index.tsx', '/index.ts'].map(suffix => base + suffix).find(fs.existsSync)
    if (dependency) visit(dependency)
  }
}
for (const entry of ['layout.tsx', 'page.tsx', 'village/page.tsx', 'not-found.tsx', 'error.tsx', 'global-error.tsx', 'loading.tsx']) visit(path.join(app, entry))
const text = [...visited].map(file => fs.readFileSync(file, 'utf8')).join('\n')
const original = fs.readFileSync(path.join(app, 'globals.css'), 'utf8').replace(/\r\n/g, '\n')
const sourceHash = createHash('sha256').update(original).digest('hex')
const header = `/* Generated from globals.css (${sourceHash}). Run npm run styles:generate; do not edit this file. */\n`
const tree = postcss.parse(original)
let allRules = 0, retainedRules = 0
const escape = value => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
function canMatch(selector) {
  // Negation and functional selector unions stay conservative. Over-retaining a
  // rule is preferable to dropping a state used by an accessible control.
  if (/:(?:not|is|where)\(/.test(selector)) return true
  let matches = false
  selectorParser(selectors => selectors.each(item => {
    const names = []
    item.walkClasses(node => names.push(node.value))
    if (names.every(name => name.startsWith('site-agent-') || name.startsWith('is-') || new RegExp(`(^|[^a-zA-Z0-9_-])${escape(name)}($|[^a-zA-Z0-9_-])`).test(text))) matches = true
  })).processSync(selector)
  return matches
}
function prune(node) {
  for (const child of [...(node.nodes || [])]) {
    if (child.type === 'atrule' && /keyframes$/.test(child.name)) continue
    if (child.type === 'rule') {
      allRules++
      if (canMatch(child.selector)) retainedRules++
      else child.remove()
    } else if (child.nodes) {
      prune(child)
      if (!child.nodes.length) child.remove()
    }
  }
}
prune(tree)
const critical = header + tree.toString().trim() + '\n'
const full = postcss.parse(original)
full.walkAtRules('tailwind', rule => rule.remove())
const secondary = header + ':root { --secondary-surface-styles: 1; }\n' + full.toString().trim() + '\n'
if (gzipSync(critical).length > 13000) throw new Error('Marketing custom CSS exceeds its 13KB gzip source budget; inspect new dependencies rather than dropping content.')
for (const [name, value] of [['marketing-critical.css', critical], ['secondary-surfaces.css', secondary]]) {
  const file = path.join(app, name)
  if (writing) fs.writeFileSync(file, value)
  else if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== value) throw new Error(`${name} needs regeneration: npm run styles:generate`)
}
// New secondary UI routes must explicitly retain the original complete styles.
for (const entry of fs.readdirSync(app, { withFileTypes: true })) {
  if (!entry.isDirectory() || ['api', 'village'].includes(entry.name)) continue
  const folder = path.join(app, entry.name)
  const hasPage = directory => fs.readdirSync(directory, { withFileTypes: true }).some(item => item.isDirectory() ? hasPage(path.join(directory, item.name)) : item.name === 'page.tsx')
  if (!hasPage(folder)) continue
  const layout = path.join(folder, 'layout.tsx')
  if (!fs.existsSync(layout) || !fs.readFileSync(layout, 'utf8').includes('secondary-surfaces.css')) throw new Error(`${entry.name}/layout.tsx must import ../secondary-surfaces.css to retain its full original styling.`)
}
console.log(JSON.stringify({ marketingStyles: 'passed', dependencyFiles: visited.size, allRules, retainedRules, sourceGzipBytes: gzipSync(critical).length, originalSourceGzipBytes: gzipSync(original).length, fullSecondaryStylesPreserved: true }))
